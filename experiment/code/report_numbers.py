"""Key numbers for experiment_report.md, extracted mechanically from results.json (no hand transcription).

    python src/report_numbers.py --results results.json --out metrics_key_numbers.md

Every number quoted in the report is in this file (or in the tables under tables/)."""
from __future__ import annotations

import argparse
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RUN = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import scenarios as sc  # noqa: E402


def f(x, nd=3, pct=False):
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "NA"
    return ("%.1f%%" % (100 * x)) if pct else (("%." + str(nd) + "f") % x if abs(x) < 1e5 else "%.3g" % x)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(RUN, "results.json"))
    ap.add_argument("--out", default=os.path.join(RUN, "metrics_key_numbers.md"))
    a = ap.parse_args(argv)
    res = json.load(open(a.results))
    scen = sc.build_scenarios()
    idx = {(r["sid"], r["method"], r["param"], r["target"]): r for r in res["metrics_table"]}
    S = {int(k): v for k, v in res["scenarios"].items()}
    prov = res["provenance"]
    L = ["# Key numbers (generated by src/report_numbers.py from results.json; do not edit)", "",
         "results.json timestamp %s, git %s, run_complete=%s, R_target=%s, rep rows %s; simulated=%s" % (
             prov.get("timestamp"), prov.get("git_sha"), prov.get("run_complete"), prov.get("R_target"),
             prov.get("n_rep_rows"), res.get("simulated")),
         "supplementary (M0-GI): %s" % json.dumps({k: v for k, v in (prov.get("supplementary") or {}).items()
                                                  if k != "note"}), ""]

    def g(s, m, p, k, t="model"):
        r = idx.get((s, m, p, t))
        return None if r is None else r.get(k)

    def rng(sids, m, p, k, pct=False):
        v = [g(s, m, p, k) for s in sids]
        v = [x for x in v if x is not None]
        return "NA" if not v else "%s to %s" % (f(min(v), pct=pct), f(max(v), pct=pct))

    blocks = {
        "core, spillover (1-4, 9-12)": [s for s in scen if scen[s].block == "core" and scen[s].params.phi > 0],
        "core, no spillover (5-8, 13-16)": [s for s in scen if scen[s].block == "core" and scen[s].params.phi == 0],
        "null (17-20)": [s for s in scen if scen[s].block == "null"],
        "misspecification (21-25)": [s for s in scen if scen[s].block == "misspec"],
    }
    L += ["## Ranges over scenarios (tau, target = generating parameter)", "",
          "| block | method | R | bias | empSE | modelSE | RMSE | coverage | reject H0 | conv |", "|---" * 10 + "|"]
    for bn, sids in blocks.items():
        sids = [s for s in sorted(sids) if s in S]
        for m in ("M0", "M0_G", "M0_GI", "M0_OI", "M0p", "M1", "M1_BC", "M2", "M3", "M4", "Oracle"):
            if not any(g(s, m, "tau", "n_ok") for s in sids):
                continue
            Rs = [g(s, m, "tau", "R") for s in sids if g(s, m, "tau", "R")]
            L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                bn, m, "%d-%d" % (min(Rs), max(Rs)) if Rs else "NA", rng(sids, m, "tau", "bias"),
                rng(sids, m, "tau", "empSE"), rng(sids, m, "tau", "modelSE"), rng(sids, m, "tau", "RMSE"),
                rng(sids, m, "tau", "coverage", True), rng(sids, m, "tau", "reject0", True),
                rng(sids, m, "tau", "conv", True)))
    L += ["", "## Per scenario: tau for M0, M0-G, M0-GI, M1 (bias [MCSE], coverage [MCSE])", "",
          "| sid | scenario | R | M0 | M0-G | M0-GI (R) | M1 | M1-BC conv | J reject | M0-G boundary | M0-GI boundary |",
          "|---" * 11 + "|"]
    for s in sorted(S):
        def bc(m):
            return "%s [%s], %s [%s]" % (f(g(s, m, "tau", "bias")), f(g(s, m, "tau", "bias_mcse"), 4),
                                        f(g(s, m, "tau", "coverage"), pct=True),
                                        f(g(s, m, "tau", "coverage_mcse"), pct=True))
        L.append("| %d | %s | %s | %s | %s | %s (%s) | %s | %s | %s | %s | %s |" % (
            s, S[s]["name"], S[s]["R"], bc("M0"), bc("M0_G"), bc("M0_GI"), g(s, "M0_GI", "tau", "R"), bc("M1"),
            f(g(s, "M1_BC", "tau", "conv"), pct=True), f((S[s].get("J_reject_05") or {}).get("p"), pct=True),
            f((S[s].get("M0G_at_boundary") or {}).get("p"), pct=True),
            f((S[s].get("M0GI_at_boundary") or {}).get("p"), pct=True)))
    L += ["", "## Per scenario: kappa, phi (M0; bias, coverage) and psi (M0, treated)", "",
          "| sid | kappa bias | kappa cov | phi bias | phi cov | psi_treated relbias (median) | cov dagger | cov pop |",
          "|---" * 8 + "|"]
    for s in sorted(S):
        L.append("| %d | %s | %s | %s | %s | %s | %s | %s |" % (
            s, f(g(s, "M0", "kappa", "bias")), f(g(s, "M0", "kappa", "coverage"), pct=True),
            f(g(s, "M0", "phi", "bias")), f(g(s, "M0", "phi", "coverage"), pct=True),
            f(g(s, "M0", "psi_treated", "relbias_median", "dagger")),
            f(g(s, "M0", "psi_treated", "coverage", "dagger"), pct=True),
            f(g(s, "M0", "psi_treated", "coverage", "population"), pct=True)))
    L += ["", "## Pre-specified criterion check for M0 (|bias| <= 2 MCSE, coverage in [0.93, 0.97]), "
          "scenarios with phi0 > 0 in core and null blocks", "",
          "| sid | param | bias | bias/MCSE | coverage | rel. SE error | passes |", "|---" * 7 + "|"]
    for s in sorted(S):
        if scen[s].block not in ("core", "null") or scen[s].params.phi == 0:
            continue
        for p in ("tau", "kappa", "phi"):
            b, mc, cv, re = (g(s, "M0", p, k) for k in ("bias", "bias_mcse", "coverage", "relerr_SE"))
            if b is None or not mc:
                continue
            ok = abs(b) <= 2 * mc and 0.93 <= cv <= 0.97
            L.append("| %d | %s | %s | %s | %s | %s | %s |" % (s, p, f(b, 4), f(b / mc, 2), f(cv, pct=True),
                                                              f(re, 3), "yes" if ok else "no"))
    if 23 in S:
        L += ["", "X3 (sid 23) M0 tau vs switcher mean: bias %s cov %s; vs first-order pseudo-true: bias %s cov %s" % (
            f(g(23, "M0", "tau", "bias", "switch_mean")), f(g(23, "M0", "tau", "coverage", "switch_mean"), pct=True),
            f(g(23, "M0", "tau", "bias", "first_order")), f(g(23, "M0", "tau", "coverage", "first_order"), pct=True))]
    if 25 in S:
        L += ["X5 (sid 25) M0-ET bins e0..e6: bias %s; coverage %s" % (
            ", ".join(f(g(25, "M0_ET", "tau_e%d" % k, "bias")) for k in range(7)),
            ", ".join(f(g(25, "M0_ET", "tau_e%d" % k, "coverage"), pct=True) for k in range(7)))]
    app = res.get("application")
    if app:
        L += ["", "## Application (%s units, G = %s states, T = %s weeks, %s to %s; t crit %s)" % (
            app["n_units"], app["G"], app["T"], app["first_week"], app["last_week"], f(app["tcrit"], 4)), "",
              "| analysis | method | tau (95% CI) | kappa (95% CI) | phi (95% CI) | boundary |", "|---" * 6 + "|"]
        for r in app["table"]:
            def ci(k):
                if r.get(k) is None:
                    return "NA"
                return "%s (%s, %s)" % (f(r[k]), f(r.get(k + "_lo")), f(r.get(k + "_hi")))
            L.append("| %s | %s | %s | %s | %s | %s |" % (r["analysis"], r["method"], ci("tau"), ci("kappa"),
                                                          ci("phi"), r.get("at_boundary", "")))
        J = app.get("J", {})
        L += ["", "M0-OI Hansen J = %s, df = %s, p = %s" % (f(J.get("J")), J.get("J_df"), f(J.get("J_p"), 4))]
        et = app.get("event_time", {})
        if et.get("ok"):
            L += ["M0-ET: " + ", ".join("%s %s (se %s)" % (b, f(et["est"][b]), f(et["se"][b])) for b in et["bins"])]
            for k, v in et.items():
                if k.startswith("average"):
                    L += ["M0-ET %s: %s (95%% CI %s, %s) [descriptive, not pre-specified]" % (
                        k, f(v["est"]), f(v["lo"]), f(v["hi"]))]
            w = et.get("joint_wald")
            if w:
                L += ["M0-ET joint Wald H0 all bins = 0: F = %s (df %s, %s), p = %s; chi2 p = %s" % (
                    f(w["F"]), w["df1"], w["df2"], f(w["p_F"], 4), f(w["p_chi2"], 4))]
        lp = app.get("lead_placebo") or {}
        if lp.get("est") is not None:
            L += ["lead placebo: est %s se %s t %s" % (f(lp["est"]), f(lp["se"]), f(lp.get("t")))]
        for m, p in (app.get("psi") or {}).items():
            L += ["psi %s by horizon (cases averted summed over all counties, first h weeks): " % m + "; ".join(
                "%d wk %s (se %s)" % (h["weeks"], f(h["est"], 0), f(h["se"], 0)) for h in p.get("by_horizon", [])) +
                "; observed cases (treated) %s" % f(p.get("observed_cases_treated"), 0)]
        d = app.get("descriptives", {})
        L += ["descriptives: " + ", ".join("%s=%s" % (k, f(v) if isinstance(v, float) else v) for k, v in d.items())]
    with open(a.out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("[report_numbers] wrote %s" % os.path.relpath(a.out, RUN))
    return 0


if __name__ == "__main__":
    sys.exit(main())
