"""Rebuild the Web Table 7 numbers and the LaTeX table from the per-replication file.

The published table was summarised with z = 1.96 critical values although the caption
states t_{G-1}. This script recomputes coverage with t_{G-1}, adds the share of
replications with more than one interior root, and writes tables/table_10_rsel.tex.

Run from the repository root:
  python -I verification/root_selection/build_rsel_table.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy import stats

ROOT = Path(__file__).resolve().parents[2]
RSEL = ROOT / "verification" / "root_selection"
TAU0 = -0.2231435513142097

# (phi0, phibar, G, adopt, N) in table order
ORDER = [
    (0.00, 0.50, 50, "feedback", 500),
    (0.05, 0.50, 50, "feedback", 500),
    (0.05, 0.25, 50, "feedback", 500),
    (0.05, 1.00, 50, "feedback", 500),
    (0.10, 0.50, 50, "feedback", 500),
    (0.10, 0.50, 50, "random", 500),
    (0.10, 0.50, 20, "feedback", 2000),
    (0.10, 0.50, 100, "feedback", 2000),
    (0.15, 0.50, 50, "feedback", 500),
]
CONFIG = [
    (0.05, 0.50, 50, "feedback", 500),
    (0.10, 0.50, 50, "feedback", 500),
    (0.15, 0.50, 50, "feedback", 500),
    (0.05, 0.25, 50, "feedback", 500),
    (0.05, 1.00, 50, "feedback", 500),
    (0.10, 0.50, 20, "feedback", 2000),
    (0.10, 0.50, 100, "feedback", 2000),
    (0.10, 0.50, 50, "random", 500),
    (0.00, 0.50, 50, "feedback", 500),
]


def coverage(tau, se, G, crit):
    ok = np.isfinite(tau) & np.isfinite(se) & (se > 0)
    return float(np.mean(np.abs(tau[ok] - TAU0) <= crit(G) * se[ok]))


def summarise(rows, G):
    tau0 = np.array([r.get("tau0", np.nan) for r in rows], float)
    se0 = np.array([r.get("se0", np.nan) for r in rows], float)
    gi = np.array([r.get("tau_gi", np.nan) for r in rows], float)
    segi = np.array([r.get("se_gi", np.nan) for r in rows], float)
    multi = np.array([r.get("n_roots") is not None and r["n_roots"] > 1 for r in rows], float)
    bnd = np.array([bool(r.get("at_boundary")) for r in rows], float)
    ok0 = np.isfinite(tau0)
    okg = np.isfinite(gi) & np.isfinite(segi) & (segi > 0)
    z = lambda _g: stats.norm.ppf(0.975)
    t = lambda g: stats.t.ppf(0.975, g - 1)
    return dict(
        n=len(rows),
        bias_m0=float(np.mean(tau0[ok0] - TAU0)),
        cov_m0_z=coverage(tau0, se0, G, z), cov_m0_t=coverage(tau0, se0, G, t),
        bias_gi=float(np.mean(gi[np.isfinite(gi)] - TAU0)),
        cov_gi_z=coverage(gi, segi, G, z), cov_gi_t=coverage(gi, segi, G, t),
        boundary=float(bnd.mean()), multi=float(multi.mean()),
        mcse_cov=float(np.sqrt(0.95 * 0.05 / len(rows))),
        n_phi0_negative=float(np.mean([(r.get("phi0") is not None and r["phi0"] < 0) for r in rows])),
    )


def fmt(x, nd=3):
    s = f"{x:.{nd}f}"
    return "$" + s + "$" if x < 0 else s


def main():
    rows_by_cell = {}
    with (RSEL / "full.jsonl").open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            rows_by_cell.setdefault(r["cell"], []).append(r)
    cfg_of = {i: CONFIG[i] for i in range(len(CONFIG))}
    out = []
    for key in ORDER:
        idx = next(i for i, c in enumerate(CONFIG) if c[:2] == key[:2] and c[2] == key[2]
                   and c[3] == key[3] and c[4] == key[4])
        out.append(dict(cell=idx, key=key, **summarise(rows_by_cell[idx], key[2])))
    summary_path = RSEL / "full_summary_tsummary.json"
    summary_path.write_text(json.dumps(out, indent=1), encoding="utf-8")

    lines = [
        "% Validation of the root-selection rules on independent designs.",
        "% Generated by verification/root_selection/build_rsel_table.py from full.jsonl.",
        r"\begin{table}[!t]",
        r"\centering",
        r"\caption{Validation of the root-selection rules on independent designs. Nine new scenarios",
        r"with a seed base separate from the main study; $R=2000$ replications each. ``Bias'' is the",
        r"mean of $\hat\tau-\tau_0$; ``Cov.'' is the coverage of the nominal 95\% $t_{G-1}$ interval;",
        r"its MCSE is at most 0.011. ``Multi'' is the share of replications with more than one",
        r"interior root of the profile; ``Boundary'' is the share in which M0-GI selected $\phi=0$.",
        r"Because M0-GI always includes $\phi=0$ as a candidate, it can select the boundary even",
        r"when Multi $=0$. The $G=20$ and $G=100$ rows also use",
        r"$N=2000$, so they do not isolate the effect of $G$.}",
        r"\label{tab:rsel}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{ccccccccccc}",
        r"\toprule",
        r" & & & & & & \multicolumn{2}{c}{M0} & \multicolumn{2}{c}{M0-GI} & \\",
        r"\cmidrule(lr){7-8}\cmidrule(lr){9-10}",
        r"$\phi_0$ & $\bar\phi$ & $G$ & adoption & $N$ & Multi & Bias & Cov. & Bias & Cov. & Boundary \\",
        r"\midrule",
    ]
    for d in out:
        phi, pb, G, ad, N = d["key"]
        lines.append(
            f"{phi:.2f} & {pb:.2f} & {G} & {ad} & {N} & {d['multi']*100:.1f}\\% & "
            f"{fmt(d['bias_m0'])} & {d['cov_m0_t']:.3f} & {fmt(d['bias_gi'])} & "
            f"{d['cov_gi_t']:.3f} & {d['boundary']*100:.0f}\\% \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    (ROOT / "tables" / "table_10_rsel.tex").write_text("\n".join(lines), encoding="utf-8")
    for d in out:
        print(d["key"], "cov_t", round(d["cov_m0_t"], 3), round(d["cov_gi_t"], 3),
              "cov_z", round(d["cov_m0_z"], 3), round(d["cov_gi_z"], 3),
              "multi", round(d["multi"], 3), "phi<0", round(d["n_phi0_negative"], 3))


if __name__ == "__main__":
    main()
